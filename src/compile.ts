// The script→flow compiler, v0. Input: a matched pair of instrumented traces
// (fixture variants 0 and 1) for one successful script. Output: a candidate
// .flow.json5 (mcp_call steps against the primitives server) + provenance.
// The observed trace is the evidence; the script is only where the trace came
// from. Fail-closed: any ambiguity is a refusal, not a guess.
//
//   flowmcp compile <traces/name.v0.json> [out-dir] [flow_name] [server_name]

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, basename } from 'node:path';
import JSON5 from 'json5';
import { flowSchema } from './flow-schema.js';
import { executeFlow } from './engine.js';
import { HTTP_STATUS, type McpResult } from './downstream.js';

interface CallError { kind: 'status' | 'isError' | 'thrown'; status?: number; text: string }
interface TraceEntry { seq: number; name: string; args: Record<string, unknown>; result: unknown; error?: CallError }
interface Run { variant: number; result: string; trace: TraceEntry[] }

class Refusal extends Error {}

function leaves(value: unknown, path = ''): Array<[string, unknown]> {
  if (value === null || typeof value !== 'object') return [[path, value]];
  const out: Array<[string, unknown]> = [];
  for (const [k, v] of Object.entries(value)) {
    out.push(...leaves(v, path ? `${path}.${k}` : k));
  }
  return out;
}

// engine path syntax: numeric segments become [n]
const enginePath = (p: string) =>
  p.split('.').map((seg) => (/^\d+$/.test(seg) ? `[${seg}]` : `.${seg}`)).join('').replace(/^\./, '');

function subst(text: string, value: unknown, replacement: string): string {
  const sv = String(value);
  if (/^\d+(\.\d+)?$/.test(sv)) {
    if (sv.length < 2) return text;
    return text.replace(new RegExp(`(?<![\\d.])${sv.replace('.', '\\.')}(?![\\d.])`, 'g'), replacement);
  }
  if (sv.length < 3) return text;
  return text.split(sv).join(replacement);
}

function findRef(trace: TraceEntry[], before: number, value: unknown): { seq: number; path: string } | null {
  for (let i = before - 1; i >= 0; i--) {
    const hit = leaves(trace[i]!.result).find(([, v]) => v === value);
    if (hit) return { seq: trace[i]!.seq, path: hit[0] };
  }
  return null;
}

interface Node {
  id: string;
  tool: string;
  args: Record<string, string>; // interpolation strings
  seqs: number[]; // original trace seqs merged into this node
  fanout?: { overId: string; slice: number; as: string; itemArgPath: string };
}

export interface CompileOpts {
  server?: string | Record<string, string>;   // one server, or tool-name -> server map
  inputHints?: Record<string, string[]>;      // input name -> example values seen
  description?: string;                       // WHEN TO USE text for the emitted flow
}

export function compile(v0: Run, v1: Run, flowName: string, sourceName: string, opts: CompileOpts = {}) {
  const { parts, provenance } = compileParts(v0, v1, flowName, sourceName, opts);
  return { flow: emitFlow(flowName, sourceName, parts), provenance };
}

// What emitFlow writes out; compilePaths edits it (absent steps, branches) first.
interface FlowParts { steps: string[]; output: string; inputBlock: string; description: string; nodeTools: Record<string, string> }

function emitFlow(flowName: string, sourceName: string, parts: FlowParts): string {
  const { steps, output, inputBlock, description } = parts;
  return `// COMPILED FLOW — generated by flowmcp compile from ${sourceName}.
// Review before use. Evidence: matched traces under two fixture variants.
{
  name: '${flowName}',
  description: ${JSON.stringify(description.slice(0, 300))},
${inputBlock}  steps: [
${steps.join('\n')}
    { id: 'render', kind: 'template', template: ${JSON.stringify(output)} },
  ],
  output: '{{steps.render}}',
}
`;
}

function compileParts(v0: Run, v1: Run, flowName: string, sourceName: string, opts: CompileOpts = {}) {
  const serverOf = (tool: string) =>
    typeof opts.server === 'object' ? (opts.server[tool] ?? 'prims') : (opts.server ?? 'prims');
  const inputHints = opts.inputHints ?? { city: ['Lisbon', 'New York'] };
  const provenance: Record<string, unknown> = { source: sourceName, flowName };
  const warnings: string[] = [];
  const dropped: string[] = [];
  const t0 = v0.trace;
  const t1 = v1.trace;
  if (t0.length !== t1.length) throw new Refusal('trace lengths differ across variants');

  // 1. classify args and dedupe identical calls
  const seen = new Map<string, number>(); // signature -> node index
  const nodes: Node[] = [];
  const seqToNode = new Map<number, number>();
  const inputs: Record<string, string> = {}; // input name -> example value
  for (let i = 0; i < t0.length; i++) {
    const call = t0[i]!;
    const call1 = t1[i]!;
    if (call.name !== call1.name) throw new Refusal(`call #${i} differs across variants (${call.name} vs ${call1.name})`);
    const sig = call.name + JSON.stringify(call.args);
    if (seen.has(sig) && JSON.stringify(t0[nodes[seen.get(sig)!]!.seqs[0]!]!.result) === JSON.stringify(call.result)) {
      seqToNode.set(call.seq, seen.get(sig)!);
      nodes[seen.get(sig)!]!.seqs.push(call.seq);
      continue; // dedupe: identical idempotent call
    }
    const args: Record<string, string> = {};
    for (const [p, v] of leaves(call.args)) {
      const v1leaf = leaves(call1.args).find(([p1]) => p1 === p)?.[1];
      // Variant 1 rewrites every string of 3+ chars in recorded results, so
      // such a string that is unchanged across variants did not come from a
      // result — a value match there is coincidence (a literal owner name
      // equal to a prior result's owner.login), not dataflow.
      const followsNoData = typeof v === 'string' && v.length >= 3 && v === v1leaf;
      let ref = followsNoData ? null : findRef(t0, i, v);
      if (ref) {
        const ref1 = findRef(t1, i, v1leaf);
        // v0 holds the value at several paths; variant 1 tags each path apart,
        // so it names the one the script read
        if (ref1 && ref1.path !== ref.path && seqToNode.get(ref1.seq) !== undefined &&
            leaves(t0.find((c) => c.seq === ref1.seq)?.result).some(([q, x]) => q === ref1.path && x === v)) {
          ref = ref1;
        }
        if (!ref1 || seqToNode.get(ref.seq) !== seqToNode.get(ref1.seq) || ref.path !== ref1.path) {
          throw new Refusal(`unstable ref for ${call.name}.${p} across variants`);
        }
        args[p] = `{{steps.n${seqToNode.get(ref.seq)}.${enginePath(ref.path)}}}`;
      } else if (v === v1leaf) {
        const hint = Object.entries(inputHints).find(([, vals]) => vals.some((x) => String(v).includes(x)));
        if (hint && typeof v === 'string') {
          const hintVal = hint[1].find((x) => v.includes(x))!;
          inputs[hint[0]] = hintVal;
          args[p] = v.split(hintVal).join(`{{input.${hint[0]}}}`);
        } else {
          args[p] = String(v);
          if (typeof v === 'number') warnings.push(`${call.name}.${p}: numeric const emitted as string`);
        }
      } else {
        throw new Refusal(`derived argument ${call.name}.${p} (${JSON.stringify(v)} vs ${JSON.stringify(v1leaf)}) — cannot represent`);
      }
    }
    const idx = nodes.length;
    nodes.push({ id: `n${idx}`, tool: call.name, args, seqs: [call.seq] });
    seen.set(sig, idx);
    seqToNode.set(call.seq, idx);
  }

  // 2. fanout detection: consecutive nodes, same tool, single distinguishing arg
  //    referencing positions 0..k-1 of one prior array-result node
  const merged: Node[] = [];
  for (let i = 0; i < nodes.length; ) {
    const run: Node[] = [nodes[i]!];
    while (i + run.length < nodes.length && nodes[i + run.length]!.tool === nodes[i]!.tool) run.push(nodes[i + run.length]!);
    const positions = run.map((n, k) => {
      const argPaths = Object.keys(n.args);
      if (argPaths.length !== 1) return null;
      const m = /^\{\{steps\.(n\d+)\.\[(\d+)\]\}\}$/.exec(n.args[argPaths[0]!]!);
      return m && Number(m[2]) === k ? { overId: m[1]!, itemArgPath: argPaths[0]! } : null;
    });
    if (run.length >= 2 && positions.every((p) => p && p.overId === positions[0]!.overId)) {
      merged.push({ id: run[0]!.id, tool: run[0]!.tool, args: {}, seqs: run.flatMap((n) => n.seqs),
        fanout: { overId: positions[0]!.overId, slice: run.length, as: 'item', itemArgPath: positions[0]!.itemArgPath } });
    } else {
      merged.push(...run);
    }
    i += run.length;
  }

  // 3. dead-call elimination: a node must feed a later arg or the final output
  const finalText = v0.result;
  const live = new Set<string>();
  const nodeById = new Map(merged.map((n) => [n.id, n]));
  const usedInOutput = (n: Node) =>
    n.seqs.some((s) => leaves(t0.find((c) => c.seq === s)!.result).some(([, v]) => v !== null && String(v).length >= 3 && finalText.includes(String(v))));
  const feeds = (id: string) => merged.some((m) => Object.values(m.args).some((a) => a.includes(`steps.${id}.`)) || m.fanout?.overId === id);
  for (const n of merged) if (usedInOutput(n) || feeds(n.id)) live.add(n.id);
  // keep transitive dependencies of live nodes
  let grew = true;
  while (grew) {
    grew = false;
    for (const n of merged) {
      if (!live.has(n.id)) continue;
      const deps = [...Object.values(n.args).join(' ').matchAll(/steps\.(n\d+)\./g)].map((m) => m[1]!);
      if (n.fanout) deps.push(n.fanout.overId);
      for (const d of deps) if (!live.has(d)) { live.add(d); grew = true; }
    }
  }
  const kept = merged.filter((n) => live.has(n.id));
  for (const n of merged) if (!live.has(n.id)) dropped.push(`${n.id} (${n.tool}) — result unused`);

  // 4. assemble inference: templatize the final answer against trace values.
  // FOLD GROUPS generalize repetition: a fanout node's per-call results, OR an
  // array-of-objects inside a single call's result (e.g. search results[]) —
  // both become a map/lines step instead of unrolled fixed slots.
  function findObjectArrays(value: unknown, path = ''): Array<[string, unknown[]]> {
    if (Array.isArray(value)) {
      return value.length >= 2 && value.every((e) => e !== null && typeof e === 'object' && !Array.isArray(e))
        ? [[path, value]]
        : [];
    }
    if (value !== null && typeof value === 'object') {
      const out: Array<[string, unknown[]]> = [];
      for (const [k, v] of Object.entries(value)) out.push(...findObjectArrays(v, path ? `${path}.${k}` : k));
      return out;
    }
    return [];
  }

  interface Group { gid: string; overExpr: string; items: unknown[] }

  type Claims = Array<{ gid: string; item: number } | null>;
  function templatize(run: Run, given?: Claims): { lines: string[]; inners: Map<string, { template: string; count: number; overExpr: string }>; claims: Claims } {
    const t = run.trace;
    const lines = run.result.split('\n');
    const groups: Group[] = [];
    const fan = kept.find((n) => n.fanout);
    if (fan) {
      groups.push({
        gid: fan.id,
        overExpr: `steps.${fan.id}`,
        items: fan.seqs.slice(0, fan.fanout!.slice).map((sq) => t.find((c) => c.seq === sq)!.result),
      });
    }
    for (const n of kept.filter((k) => !k.fanout)) {
      const res = t.find((c) => c.seq === n.seqs[0]!)!.result;
      for (const [ap, arr] of findObjectArrays(res)) {
        groups.push({ gid: `${n.id}${ap ? '_' + ap.replace(/[^A-Za-z0-9]+/g, '_') : ''}`, overExpr: `steps.${n.id}${ap ? '.' + enginePath(ap) : ''}`, items: arr });
      }
    }

    const claimedBy: Array<{ gid: string; item: number } | null> = lines.map(() => null);
    const inners = new Map<string, { template: string; count: number; overExpr: string }>();

    for (const g of groups) {
      const distinctive = (item: unknown, line: string) =>
        leaves(item).some(([, v]) => v !== null && String(v).length >= 3 && line.includes(String(v)));
      const hits: Array<{ lineIdx: number; item: number }> = [];
      lines.forEach((line, li) => {
        if (given) {
          const c = given[li];
          if (c?.gid === g.gid) hits.push({ lineIdx: li, item: c.item });
          return;
        }
        if (claimedBy[li]) return;
        const matches = g.items.map((it, k) => (distinctive(it, line) ? k : -1)).filter((k) => k >= 0);
        if (matches.length === 1) hits.push({ lineIdx: li, item: matches[0]! });
      });
      if (hits.length < 2) continue; // nothing repetitive to fold for this group
      const itemsSeen = [...new Set(hits.map((h) => h.item))].sort((a, b) => a - b);
      const contiguous = itemsSeen.every((v, i) => v === i);
      if (!contiguous) {
        throw new Refusal(
          `group ${g.gid}: observed non-contiguous item selection [${itemsSeen.join(',')}] — the script's selection logic (e.g. cross-query dedupe) is not representable; unrolled emission would break when live data has fewer items. Re-author with a contiguous take-N, or hand-write this flow.`,
        );
      }
      // BLOCK-based: an item may render as several lines (title + snippet).
      // Extend each item's claim to the contiguous run following its first hit
      // that contains no other item's values and is non-empty.
      const byItem = new Map<number, number[]>();
      for (const h of hits) {
        if (!byItem.has(h.item)) byItem.set(h.item, []);
        byItem.get(h.item)!.push(h.lineIdx);
      }
      const blockLines = new Map<number, number[]>(); // item -> line indexes
      for (const [item, idxs] of byItem) {
        const all = new Set(idxs);
        const startLine = Math.min(...idxs);
        const endLine = Math.max(...idxs);
        for (let li = startLine; li <= endLine; li++) all.add(li); // fill interior gaps
        blockLines.set(item, [...all].sort((a, b) => a - b));
      }
      const templates = new Set(
        [...blockLines].map(([item, idxs]) => {
          let block = idxs.map((li) => lines[li]!).join('\n');
          for (const [p, v] of leaves(g.items[item]!).sort((a, b) => String(b[1]).length - String(a[1]).length)) {
            if (v !== null) block = subst(block, v, `{{it.${enginePath(p)}}}`);
          }
          return block.replace(new RegExp(`(?<!\\d)${item + 1}(?!\\d)`, 'g'), 'ORD');
        }),
      );
      if (templates.size !== 1) {
        throw new Refusal(
          `group ${g.gid}: per-item blocks not structurally identical (${templates.size} shapes) — unrolled emission would be fragile on live data. Re-author for uniform per-item rendering, or hand-write this flow.`,
        );
      }
      for (const [item, idxs] of blockLines) for (const li of idxs) claimedBy[li] = { gid: g.gid, item };
      inners.set(g.gid, { template: [...templates][0]!, count: itemsSeen.length, overExpr: g.overExpr });
    }

    // rebuild outer: first claimed line of each folded group becomes its marker
    const emitted = new Set<string>();
    const outLines: string[] = [];
    lines.forEach((line, li) => {
      const c = claimedBy[li];
      if (c && inners.has(c.gid)) {
        if (!emitted.has(c.gid)) { outLines.push(`@@G_${c.gid}@@`); emitted.add(c.gid); }
        return;
      }
      outLines.push(line);
    });
    return { lines: outLines, inners, claims: claimedBy };
  }

  // Outer text: trace values become step refs, both variants in lockstep, line
  // by line. A v0 value that is still in the v1 line after that line's v1 data
  // is replaced is literal text there (variant 1 rewrites every result string),
  // so it stays literal in v0 too — a heading that spells out the repo name
  // must not turn into a ref to a result's full_name that happens to equal it.
  function substOuter(l0: string[], l1: string[]): { outer0: string; outer1: string } {
    const pairs: Array<{ x0: unknown; x1: unknown; ref: string }> = [];
    for (const n of kept.filter((k) => !k.fanout)) {
      for (const sq of n.seqs) {
        const leaves1 = new Map(leaves(t1.find((c) => c.seq === sq)?.result));
        for (const [p, x0] of leaves(t0.find((c) => c.seq === sq)!.result)) {
          if (x0 !== null) pairs.push({ x0, x1: leaves1.get(p), ref: `{{steps.${n.id}.${enginePath(p)}}}` });
        }
      }
    }
    pairs.sort((a, b) => String(b.x0).length - String(a.x0).length);
    // values spanning lines (PR bodies) cannot be matched per line: whole text
    let j0 = l0.join('\n');
    let j1 = l1.join('\n');
    const multi = pairs.filter((q) => String(q.x0).includes('\n'));
    for (const { x0, x1, ref } of multi) {
      j0 = subst(j0, x0, ref);
      if (x1 !== undefined && x1 !== null) j1 = subst(j1, x1, ref);
    }
    const out0 = j0.split('\n');
    const out1 = j1.split('\n');
    const lockstep = out0.length === out1.length;
    for (const { x0, x1, ref } of pairs.filter((q) => !String(q.x0).includes('\n'))) {
      for (let li = 0; li < out0.length; li++) {
        let literalHere = false;
        if (lockstep && x1 !== undefined && x1 !== null) {
          const after = subst(out1[li]!, x1, ref);
          literalHere = String(x0) !== String(x1) && subst(after, x0, '\u0000') !== after;
          out1[li] = after;
        }
        if (!literalHere) out0[li] = subst(out0[li]!, x0, ref);
      }
      if (!lockstep && x1 !== undefined && x1 !== null) {
        for (let li = 0; li < out1.length; li++) out1[li] = subst(out1[li]!, x1, ref);
      }
    }
    return { outer0: out0.join('\n'), outer1: out1.join('\n') };
  }
  // Which line renders which item is read off variant 1, where every string is
  // tagged by its path: in variant 0 a short value can recur by chance (a PR
  // title that quotes another's text) and make a line look ambiguous.
  const lineCount = v0.result.split('\n').length === v1.result.split('\n').length;
  const t1v = templatize(v1);
  const t0v = templatize(v0, lineCount ? t1v.claims : undefined);
  const { outer0, outer1 } = substOuter(t0v.lines, t1v.lines);
  const a0 = { outer: outer0, inners: t0v.inners };
  const a1 = { outer: outer1, inners: t1v.inners };
  const innersEqual =
    a0.inners.size === a1.inners.size &&
    [...a0.inners].every(([gid, v]) => a1.inners.get(gid)?.template === v.template && a1.inners.get(gid)?.count === v.count);
  if (a0.outer !== a1.outer || !innersEqual) {
    throw new Refusal('assemble: templates differ across variants — output not fully explained by trace values');
  }

  // input substitution into templates: the promoted input value appears in the
  // output too (titles, headers) — parameterize it there as well
  const substInputs = (text: string) => {
    let out = text;
    for (const [name, ex] of Object.entries(inputs)) out = subst(out, ex, `{{input.${name}}}`);
    return out;
  };

  // 5. emit flow
  const steps: string[] = [];
  for (const n of kept) {
    if (n.fanout) {
      steps.push(`    { id: '${n.id}', kind: 'map', over: 'steps.${n.fanout.overId}[0:${n.fanout.slice}]', as: 'x',
      step: { kind: 'mcp_call', server: '${serverOf(n.tool)}', tool: '${n.tool}', args: { ${n.fanout.itemArgPath}: '{{x}}' } } },`);
    } else {
      const args = Object.entries(n.args).map(([p, v]) => `${p.includes('.') ? `'${p}'` : p}: '${v}'`).join(', ');
      // Later steps read into this result, so the default 8K cap (which cuts
      // it to a string) would break them on live data — five GitHub PR objects
      // are ~100K. Sized from the recording, with headroom for bigger live data.
      const recorded = JSON.stringify(t0.find((c) => c.seq === n.seqs[0])?.result ?? '').length;
      const cap = recorded > 2_000 ? `, maxResultChars: ${Math.min(1_000_000, Math.max(500_000, recorded * 4))}` : '';
      steps.push(`    { id: '${n.id}', kind: 'mcp_call', server: '${serverOf(n.tool)}', tool: '${n.tool}'${args ? `, args: { ${args} }` : ''}${cap} },`);
    }
  }
  let output = a0.outer;
  for (const [gid, inner] of a0.inners) {
    let innerTemplate = substInputs(inner.template);
    if (innerTemplate.includes('ORD')) {
      warnings.push('per-item ordinal numbering dropped: the flow DSL map has no loop index; emitted as list dashes');
      innerTemplate = innerTemplate.replace(/^\s*(?:[A-Za-z]+ )?ORD[.):]?\s*/, '- ').replace(/ORD/g, '');
    }
    const stepId = `lines_${gid}`;
    steps.push(`    { id: '${stepId}', kind: 'map', over: '${inner.overExpr}[0:${inner.count}]', as: 'it',
      step: { kind: 'template', template: ${JSON.stringify(innerTemplate)} } },`);
    output = output.replace(`@@G_${gid}@@`, `{{steps.${stepId}}}`);
  }
  output = substInputs(output);
  const inputBlock = Object.keys(inputs).length
    ? `  input: {\n${Object.entries(inputs).map(([k, ex]) => `    ${k}: { type: 'string', description: ${JSON.stringify(`Observed values include ${ex}`)}, required: false, default: ${JSON.stringify(ex)} },`).join('\n')}\n  },\n`
    : '  input: {},\n';
  // The description does the model's selection work — that is the thesis. A
  // provenance sentence cannot select, so without an operator-supplied
  // description we emit a loud placeholder (behavior summary, REVIEW marker)
  // and warn. Provenance belongs in provenance.json and the header comment.
  let description = opts.description;
  if (!description) {
    const toolSummary = [...new Set(kept.map((n) => n.tool))].join(', ');
    description = `WHEN TO USE: [REVIEW: replace with task-selection guidance before promotion] Runs the recorded procedure: ${toolSummary}.`;
    warnings.push(
      'no description supplied — emitted a placeholder; the description is what lets a model select this flow, so replace it before promotion',
    );
  }
  provenance.warnings = warnings;
  provenance.droppedCalls = dropped;
  provenance.dedupedCalls = merged.filter((n) => n.seqs.length > (n.fanout ? n.fanout.slice : 1)).map((n) => n.id);
  provenance.nodes = kept.length;
  const nodeTools = Object.fromEntries(kept.map((n) => [n.id, n.tool]));
  return { parts: { steps, output, inputBlock, description, nodeTools } as FlowParts, provenance };
}

// ---- several input sets: a read's "not found" becomes an `absent` step ----
//
// One recording per input set. The run where every call succeeded compiles as
// above. A run where exactly one call failed with a "not found" shows what the
// script prints without that call's data; the flow gets `absent` on the call
// and a branch for that output region. The evidence is the render: the flow is
// executed against each recording and must reproduce what the script printed.

export interface Path { input: Record<string, string>; v0: Run; v1: Run }

// "not found" only: 401/403/429 are failures the flow must surface, not data
const ABSENT_STATUSES = [404, 410];

// Serve a recording to the engine, as the downstream servers returned it.
function recordedPool(trace: TraceEntry[]) {
  const norm = (v: unknown): unknown =>
    v !== null && typeof v === 'object'
      ? Object.fromEntries(Object.entries(v).sort(([a], [b]) => a.localeCompare(b)).map(([k, x]) => [k, norm(x)]))
      : String(v);
  const sig = (tool: string, args: unknown) => `${tool}|${JSON.stringify(norm(args ?? {}))}`;
  const bySig = new Map(trace.map((c) => [sig(c.name, c.args), c]));
  return {
    has: () => true,
    call: async (_server: string, tool: string, args: Record<string, unknown>): Promise<McpResult> => {
      const c = bySig.get(sig(tool, args));
      if (!c) throw new Error(`the flow calls ${tool}(${JSON.stringify(args)}), which the recording never made`);
      if (c.error) {
        return { isError: true, content: [{ type: 'text', text: c.error.text }], ...(c.error.status ? { [HTTP_STATUS]: c.error.status } : {}) };
      }
      return typeof c.result === 'string'
        ? { content: [{ type: 'text', text: c.result }] }
        : { content: [], structuredContent: c.result as Record<string, unknown> };
    },
  };
}

async function render(flowText: string, path: Path, variant: 0 | 1): Promise<string> {
  const flow = flowSchema.parse(JSON5.parse(flowText));
  const run = await executeFlow(flow, path.input, { mcp: recordedPool((variant ? path.v1 : path.v0).trace) as never });
  if (run.status !== 'complete') throw new Refusal('a read-only flow paused for approval');
  return run.text;
}

export async function compilePaths(paths: Path[], flowName: string, sourceName: string, opts: CompileOpts = {}) {
  const failed = (p: Path) => p.v0.trace.filter((c) => c.error);
  const base = paths.find((p) => failed(p).length === 0 && failed({ ...p, v0: p.v1 }).length === 0);
  if (!base) throw new Refusal('no input set ran without a failed call — the flow needs one run that saw every result');
  const { parts, provenance } = compileParts(base.v0, base.v1, flowName, sourceName, opts);
  const warnings = provenance.warnings as string[];
  const emit = () => emitFlow(flowName, sourceName, parts);
  // Exact when the flow reproduces the script's own output; not when the
  // compiler had to approximate it (a dropped list numbering).
  const exact = (await render(emit(), base, 0)) === base.v0.result;
  const absentNodes: Array<{ step: string; tool: string; absent: number[] | 'any-error'; input: Record<string, string> }> = [];

  for (const p of paths) {
    const fails = failed(p);
    if (fails.length === 0) continue;
    const where = `input ${JSON.stringify(p.input)}`;
    if (fails.length > 1) throw new Refusal(`${where}: ${fails.length} calls failed (${fails.map((c) => c.name).join(', ')}) — only one absent call per input set is supported`);
    const call = fails[0]!;
    const call1 = p.v1.trace.find((c) => c.seq === call.seq);
    if (!call1?.error || call1.name !== call.name) throw new Refusal(`${where}: the failed call differs across variants`);
    const e = call.error!;
    let absent: number[] | 'any-error';
    if (e.kind === 'status' && ABSENT_STATUSES.includes(e.status!)) absent = [e.status!];
    else if (e.kind === 'isError') absent = 'any-error';
    else throw new Refusal(`${where}: ${call.name} failed (${e.status ? `HTTP ${e.status}` : e.kind}: ${e.text.slice(0, 120)}) — only a "not found" (${ABSENT_STATUSES.join('/')}) can be compiled as absent`);

    // the base node for the failed call: same tool, same input-only arguments
    const own = (id: string) => parts.steps.findIndex((l) => l.startsWith(`    { id: '${id}', kind: 'mcp_call'`));
    const argsOf = (line: string) => [...line.matchAll(/(\w+|'[^']+'): '([^']*)'/g)];
    const candidates = Object.entries(parts.nodeTools).filter(([id, tool]) => {
      if (tool !== call.name || own(id) === -1) return false;
      return argsOf(parts.steps[own(id)]!.slice(parts.steps[own(id)]!.indexOf('args:'))).every(([, k, v]) => {
        if (/\{\{steps\./.test(v!)) return true;
        const filled = v!.replace(/\{\{input\.(\w+)\}\}/g, (_, n: string) => p.input[n] ?? '');
        return String(call.args[k!.replace(/'/g, '')]) === filled;
      });
    });
    if (candidates.length !== 1) throw new Refusal(`${where}: the failed ${call.name} call matches ${candidates.length} steps of the flow`);
    const id = candidates[0]![0];
    if (absentNodes.some((a) => a.step === id)) continue; // already compiled from another input; verified below
    const ref = new RegExp(`steps\\.${id}(?![\\w])`);
    const readers = parts.steps.filter((l, i) => i !== own(id) && ref.test(l));
    if (readers.length) throw new Refusal(`${where}: ${call.name} failed, but later steps read its result — only a call whose data goes straight to the output can be absent`);
    const lines = parts.output.split('\n');
    const hit = lines.map((l, i) => (ref.test(l) ? i : -1)).filter((i) => i >= 0);
    if (!hit.length) throw new Refusal(`${where}: ${call.name} failed, but its data never reaches the output`);
    const [from, to] = [hit[0]!, hit[hit.length - 1]!];

    // The branch: else is the base's lines; then is what the script printed
    // there instead, read off this run between the text around the region.
    const MARK = '\u0001FALLBACK\u0001';
    const branchLine = (fallback: string) =>
      `    { id: '${id}_absent', kind: 'branch', if: 'steps.${id} == null',\n` +
      `      then: [{ id: '${id}_none', kind: 'template', template: ${JSON.stringify(fallback)} }],\n` +
      `      else: [{ id: '${id}_some', kind: 'template', template: ${JSON.stringify(lines.slice(from, to + 1).join('\n'))} }] },`;
    const stepLine = parts.steps[own(id)]!.replace(/ },$/, `, absent: ${JSON.stringify(absent)} },`);
    parts.steps = [...parts.steps.slice(0, own(id)), stepLine, branchLine(MARK), ...parts.steps.slice(own(id) + 1)];
    parts.output = [...lines.slice(0, from), `{{steps.${id}_none}}{{steps.${id}_some}}`, ...lines.slice(to + 1)].join('\n');
    const after = lines.slice(to + 1);
    const anchor = after.slice(0, Math.max(0, after.findIndex((l) => l.includes('{{')))).join('\n');
    const fallbackFor = async (variant: 0 | 1) => {
      const printed = (variant ? p.v1 : p.v0).result;
      const rendered = await render(emit(), p, variant);
      const [pre, post] = rendered.split(MARK) as [string, string];
      if (!printed.startsWith(pre)) throw new Refusal(`${where}: the output before ${call.name}'s region does not match what the script printed`);
      if (printed.endsWith(post) && printed.length >= pre.length + post.length) return printed.slice(pre.length, printed.length - post.length);
      const end = anchor.trim() && post.startsWith('\n' + anchor) ? printed.indexOf('\n' + anchor, pre.length) : -1;
      if (end === -1) throw new Refusal(`${where}: cannot find where the script's fallback for ${call.name} ends`);
      return printed.slice(pre.length, end);
    };
    const f0 = await fallbackFor(0);
    // variant 1 changes strings, not numbers: check the run's values directly too
    const leak = p.v0.trace.flatMap((c) => (c.error ? [] : leaves(c.result)))
      .find(([, v]) => v !== null && typeof v !== 'boolean' && !Object.values(p.input).includes(String(v)) && subst(f0, v, '\u0000') !== f0);
    if (leak) throw new Refusal(`${where}: what the script prints without ${call.name} depends on other tool data (${JSON.stringify(leak[1])}) — only fixed text (and inputs) can be compiled`);
    if (f0 !== (await fallbackFor(1))) throw new Refusal(`${where}: what the script prints without ${call.name} depends on other tool data — only fixed text (and inputs) can be compiled`);
    let fallback = f0;
    for (const [n, v] of Object.entries(p.input).sort((a, b) => b[1].length - a[1].length)) fallback = subst(fallback, v, `{{input.${n}}}`);
    if (/\{\{(?!input\.)/.test(fallback)) throw new Refusal(`${where}: the fallback text contains template syntax`);
    parts.steps = parts.steps.map((l) => (l === branchLine(MARK) ? branchLine(fallback) : l));
    absentNodes.push({ step: id, tool: call.name, absent, input: p.input });
  }

  // Every recording, both variants: the flow must print what the script did.
  if (exact) {
    for (const p of paths) for (const v of [0, 1] as const) {
      if ((await render(emit(), p, v)) !== (v ? p.v1 : p.v0).result) {
        throw new Refusal(`input ${JSON.stringify(p.input)} (variant ${v}): the flow's output differs from what the script printed`);
      }
    }
  } else if (paths.length > 1) {
    warnings.push('the flow approximates the script\'s output (e.g. dropped numbering), so other input sets were checked only around their absent regions');
    // name what differs, so a reviewer sees e.g. an empty-list fallback the flow lacks
    const unnumbered = (l: string) => l.replace(/^\s*\d+[.)]\s+/, '- ');
    for (const p of paths.filter((q) => q !== base)) {
      const got = (await render(emit(), p, 0)).split('\n');
      const want = p.v0.result.split('\n');
      const i = want.findIndex((l, k) => unnumbered(l) !== unnumbered(got[k] ?? ''));
      if (i !== -1) warnings.push(`input ${JSON.stringify(p.input)}: line ${i + 1} — the script printed ${JSON.stringify(want[i])}, the flow prints ${JSON.stringify(got[i] ?? '')}`);
    }
  }
  provenance.absent = absentNodes;
  return { flow: emit(), provenance };
}

// CLI — exported for the `flowmcp compile` subcommand; the entry guard below
// covers direct execution.
export function compileCli(): void {
  if (!process.argv[2]) {
    console.error('usage: flowmcp compile <run.v0.json> [outDir] [flowName] [serverName]');
    process.exit(1);
  }
  const v0Path = process.argv[2]!;
  const outDir = process.argv[3] ?? 'compiled';
  const flowName = process.argv[4] ?? 'compiled_flow';
  const serverName = process.argv[5] ?? 'server';
  const v0 = JSON.parse(readFileSync(v0Path, 'utf8')) as Run;
  const v1 = JSON.parse(readFileSync(v0Path.replace('.v0.', '.v1.'), 'utf8')) as Run;
  mkdirSync(outDir, { recursive: true });
  try {
    const { flow, provenance } = compile(v0, v1, flowName, basename(v0Path), { server: serverName });
    writeFileSync(join(outDir, `${flowName}.flow.json5`), flow);
    writeFileSync(join(outDir, `${flowName}.provenance.json`), JSON.stringify(provenance, null, 2));
    console.log(`compiled → ${join(outDir, `${flowName}.flow.json5`)}`);
    console.log(JSON.stringify(provenance));
  } catch (e) {
    if (e instanceof Refusal) {
      console.log(`REFUSED: ${e.message}`);
      process.exit(2);
    }
    throw e;
  }
}

if ((process.argv[1]?.endsWith('compile.ts') || process.argv[1]?.endsWith('compile.js')) && process.argv[2]) {
  compileCli();
}
